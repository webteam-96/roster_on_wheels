    public async Task SendScopedEmailWithAttachmentAsync(string toEmail, string subject, string htmlBody, byte[] attachment, string attachmentFileName,
        IEnumerable<string>? ccEmails, int? clubId, int? districtId, string emailType)
    {
        string? joinedCc = null;
        if (ccEmails != null)
        {
            var list = ccEmails
                .Where(c => !string.IsNullOrWhiteSpace(c))
                .Select(c => c.Trim())
                .Where(c => !string.Equals(c, toEmail, StringComparison.OrdinalIgnoreCase))
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
            if (list.Count > 0) joinedCc = string.Join(",", list);
        }

        long? logId = null;
        try
        {
            logId = await BrevoEmailLog.InsertPendingAsync(_configuration, toEmail, joinedCc, subject, htmlBody, emailType, _logger, clubId, districtId);
            var brevoMessageId = await SendViaBrevoAsync(toEmail, subject, htmlBody, joinedCc, attachment, attachmentFileName);
