    public async Task SendEmailWithAttachmentAsync(string toEmail, string subject, string htmlBody, byte[] attachment, string attachmentFileName, IEnumerable<string>? ccEmails)
    {
        string? joinedCc = null;
        if (ccEmails != null)
        {
            var list = ccEmails
                .Where(c => !string.IsNullOrWhiteSpace(c))
                .Select(c => c.Trim())
                .Where(c => !string.Equals(c, toEmail, StringComparison.OrdinalIgnoreCase))
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .ToList();
            if (list.Count > 0) joinedCc = string.Join(",", list);
        }

        long? logId = null;
        try
        {
            // Subject usually carries the context (e.g. "Club Monthly Report - MMM YYYY"); classify by it,
            // then append " (with attachment)" only when classification falls back to "Other".
            var classified = BrevoEmailLog.ClassifyType(subject);
            var typeForLog = classified == "Other" ? "Attachment" : classified;
            logId = await BrevoEmailLog.InsertPendingAsync(_configuration, toEmail, joinedCc, subject, htmlBody, typeForLog, _logger);
            var brevoMessageId = await SendViaBrevoAsync(toEmail, subject, htmlBody, joinedCc, attachment, attachmentFileName);
            await BrevoEmailLog.MarkSentAsync(_configuration, logId, brevoMessageId, _logger);
            _logger.LogInformation("Email with attachment sent to {Email} (Brevo id={Id})", LogMask.Email(toEmail), brevoMessageId);
        }
        catch (Exception ex)
        {
            await BrevoEmailLog.MarkFailedAsync(_configuration, logId, ex.Message, _logger);
            _logger.LogError(ex, "Failed to send email with attachment to {Email}", LogMask.Email(toEmail));
            throw;
        }
    }

    // Scoped variant of SendEmailWithAttachmentAsync (additive, 2026-09-17): identical send, but the
