            _logger.LogInformation("Scoped email with attachment sent to {Email} (Brevo id={Id})", LogMask.Email(toEmail), brevoMessageId);
        }
        catch (Exception ex)
        {
            await BrevoEmailLog.MarkFailedAsync(_configuration, logId, ex.Message, _logger);
            _logger.LogError(ex, "Failed to send scoped email with attachment to {Email}", LogMask.Email(toEmail));
            throw;
        }
    }

