/**
 * Port of EmailService.cs. Transactional email goes through Brevo's HTTP API
 * (Brevo:ApiKey in the environment, sender from Brevo:SenderEmail /
 * Brevo:SenderName, which default to the brand). Every send is recorded in
 * email_log: Pending before the call, then Sent or Failed.
 *
 * The header and footer come from the brand (Look.EmailHeaderHtml /
 * EmailFooterHtml, else built from the logo and product name). Template
 * methods are ported together with the module that sends them.
 */

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/'/g, "&#39;");

export function emailHeader(): string {
  const b = Brand.Current;
  if (b.look.emailHeaderHtml) return b.look.emailHeaderHtml;
  const logo = b.look.logoUrl ? (/^https?:\/\//.test(b.look.logoUrl) ? b.look.logoUrl : `${b.domains.adminOrigin}${b.look.logoUrl}`) : "";
  const mark = logo && /^https?:\/\//.test(logo)
    ? `<img src='${logo}' alt='${esc(b.productName)}' style='height: 77px;' />`
    : `<span style='color: #ffffff; font-size: 22px; font-weight: bold;'>${esc(b.productName)}</span>`;
  return `
            <html>
            <body style='font-family: Arial, sans-serif; line-height: 1.6; color: #333; background-color: #f5f5f5; margin: 0; padding: 0;'>
                <div style='max-width: 620px; margin: 0 auto;'>
                    <div style='background-color: #1a365d; padding: 16px 24px; text-align: center; border-radius: 8px 8px 0 0;'>
                        ${mark}
                    </div>
                    <div style='background-color: #ffffff; padding: 28px 32px; border-left: 1px solid #e2e8f0; border-right: 1px solid #e2e8f0;'>`;
}

export function emailFooter(): string {
  const b = Brand.Current;
  if (b.look.emailFooterHtml) return b.look.emailFooterHtml;
  return `
                    </div>
                    <div style='background-color: #f8f9fa; border: 1px solid #e2e8f0; border-top: none; padding: 16px 24px; text-align: center; border-radius: 0 0 8px 8px;'>
                        <p style='font-size: 12px; color: #666; margin: 0; font-style: italic;'>This is generated by <strong>${esc(b.productName)}</strong></p>
                    </div>
                </div>
            </body>
            </html>`;
}

/** Best-effort classification of a send by its subject (email_log.email_type). More specific first. */
export function classifyEmailType(subject: string | null | undefined): string {
  if (!subject || !subject.trim()) return "Other";
  const s = subject;
  const has = (t: string) => s.toLowerCase().includes(t.toLowerCase());
  if (has("Mass Email")) return "Mass Email";
  if (s.includes("OTP") || has("One Time Password")) return "OTP";
  if (has("Data Collection") || has("District Directory") || has("Submission Received")) return "Data Collection";
  if (has("Auto Calculate") || has("District awards Points") || has("Citation")) return "Citation";
  if (has("Monthly Report") || has("CMR")) return "Monthly Report";
  if (has("Newsletter") || has("eBulletin")) return "Newsletter";
  if (has("Beneficiary")) return "Beneficiary";
  if (has("Payment Account")) return "Payments";
  if (has("Club Website") || has("Website")) return "Club Website";
  if (has("Password Reset") || has("Reset Password")) return "Password Reset";
  if (has("Password Changed")) return "Password Changed";
  if (has("SuperAdmin")) return "SuperAdmin";
  if (has("Zonal Co-ordinator") || has("Zonal Coordinator")) return "Zonal Coordinator";
  if (has("Club Admin") && has("Designation")) return "Club Admin Assignment";
  if (has("Login Credentials") || has("Login Details")) return "Login Credentials";
  if (has("Welcome")) return "Welcome";
  if (has("Removed") || has("Revoked")) return "Role / Membership Removed";
  if (has("Club Leadership") || has("Leadership")) return "Club Leadership";
  if (has("Reminder")) return "Reminder";
  return "Other";
}

