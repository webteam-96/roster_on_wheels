  /** The private SendEmailAsync: log Pending, send, log Sent/Failed. Never throws unless asked. */
  async send(toEmail: string, subject: string, htmlBody: string, options: SendOptions = {}): Promise<void> {
    let logId: number | null = null;
    try {
      logId = await this.insertPending(toEmail, options.ccEmail ?? null, subject, htmlBody, classifyEmailType(subject), options.clubId ?? null, options.districtId ?? null);
      const messageId = await this.sendViaBrevo(toEmail, subject, htmlBody, options.ccEmail ?? null, options.attachment ?? null);
      await this.markSent(logId, messageId);
      this.log.log(`Email sent to ${toEmail} (Brevo id=${messageId ?? ""})`);
    } catch (e) {
      const err = e as Error;
      await this.markFailed(logId, err.message);
      this.log.error(`Failed to send email to ${toEmail}: ${err.message}`);
      if (options.throwOnFailure) throw e;
    }
  }

  private async sendViaBrevo(toEmail: string, subject: string, htmlBody: string, ccEmail: string | null, attachment: { bytes: Buffer; fileName: string } | null): Promise<string | null> {
    const apiKey = this.config.get("Brevo:ApiKey");
    if (!apiKey) throw new InvalidOperationException("Brevo:ApiKey is not configured.");
    const apiUrl = this.config.get("Brevo:ApiUrl") ?? "https://api.brevo.com/v3/smtp/email";
    const senderEmail = this.config.get("Brevo:SenderEmail") ?? Brand.Current.support.noReplyEmail;
    const senderName = this.config.get("Brevo:SenderName") ?? Brand.Current.productName;
    if (!senderEmail) throw new InvalidOperationException("Brevo:SenderEmail is not configured.");

    const cc = (ccEmail ?? "")
      .split(/[,;]/)
      .map((a) => a.trim())
      .filter((a) => a && a.toLowerCase() !== toEmail.toLowerCase())
      .map((email) => ({ email }));

    const payload: Record<string, unknown> = {
      sender: { name: senderName, email: senderEmail },
      to: [{ email: toEmail }],
      subject,
      htmlContent: htmlBody,
    };
    if (cc.length) payload.cc = cc;
    if (attachment) payload.attachment = [{ name: attachment.fileName, content: attachment.bytes.toString("base64") }];

    // Large attachments (photo-rich PDFs) need far longer than a plain email.
    const timeoutSec = attachment && attachment.bytes.length > 0 ? this.config.getInt("Brevo:AttachmentTimeoutSeconds", 180) : 30;
    const resp = await fetch(apiUrl, {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json", "api-key": apiKey },
      body: JSON.stringify(payload),
      signal: AbortSignal.timeout(timeoutSec * 1000),
    });
    const text = await resp.text();
    if (!resp.ok) throw new HttpRequestException(`Brevo ${resp.status}: ${text}`);
    try {
      const id = JSON.parse(text)?.messageId;
      return typeof id === "string" ? id : null;
    } catch {
      return null; // messageId is optional metadata
    }
  }

