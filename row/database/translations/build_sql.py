"""Builds the UI label glossary SQL from ui-labels-*.json (English label -> fr de it ja ko pt es).

    python -I row/database/translations/build_sql.py

Writes database/maintenance/2026-11-12-ui-label-glossary.sql and its -down.sql. Rows go into translation_memory as
is_override = 1, provider = 'glossary', so they beat machine translation (LibreTranslate, DeepL) the same way a
correction from Settings > Translations does. A label someone already corrected by hand (provider = 'correction') is
left alone. Keys must be the exact English text the web or app shows; a key found in neither codebase is reported.
"""
import json, pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
ROW = HERE.parents[1]
LANGS = ["fr", "de", "it", "ja", "ko", "pt", "es"]
OUT = ROW / 'database' / 'maintenance' / '2026-11-12-ui-label-glossary.sql'

code = (ROW / 'mobile/lib/core/i18n/ui_strings.g.dart').read_text(encoding='utf-8')
code += ''.join(p.read_text(encoding='utf-8', errors='ignore') for p in (ROW / 'admin/src').rglob('*.ts*'))
code += ''.join(p.read_text(encoding='utf-8') for p in (ROW / 'admin/messages/en').glob('*.json'))


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "''") + "'"


rows, problems, seen = [], [], set()
for f in sorted(HERE.glob('ui-labels-*.json')):
    data = json.loads(f.read_text(encoding='utf-8'))
    for en, tr in data.items():
        if en.startswith('_'):
            continue
        if en in seen:
            problems.append(f'{f.name}: duplicate {en!r}')
            continue
        seen.add(en)
        if not (isinstance(tr, list) and len(tr) == len(LANGS) and all(isinstance(t, str) and t.strip() for t in tr)):
            problems.append(f'{f.name}: {en!r} needs {len(LANGS)} translations')
            continue
        # Source escapes line breaks and apostrophes (\n, \', &apos;); the screen shows the plain text.
        if not any(v in code for v in (en, en.replace('\n', '\\n'), en.replace("'", "\\'"), en.replace("'", '&apos;'))):
            problems.append(f'{f.name}: {en!r} not found in web or app code')
        # A placeholder or star in the English must survive (the API refuses corrections that lose one).
        for mark in re.findall(r'\{\w+\}|\*', en):
            for lang, t in zip(LANGS, tr):
                if t.count(mark) != en.count(mark):
                    problems.append(f'{f.name}: {en!r} [{lang}] lost {mark}')
        rows += [(en, lang, t) for lang, t in zip(LANGS, tr)]

values = ',\n'.join(f"(SHA2({q(en)}, 256), '{lang}', {q(en)}, {q(t)}, 'glossary', 1, UTC_TIMESTAMP(), UTC_TIMESTAMP())"
                    for en, lang, t in rows)
OUT.write_text(f"""-- UI label glossary: reviewed translations of short web and app labels into the eight launch languages.
-- Generated by row/database/translations/build_sql.py from ui-labels-*.json; edit those and rebuild, not this file.
-- Machine translation gets one- and two-word labels wrong ("Club" -> "(주)" in Korean), so these rows win over it.
-- A label corrected by hand in Settings > Translations (provider 'correction') is kept. Safe to run again.
-- After running: recycle the API app pool (it caches translations in memory). Undo: 2026-11-12-ui-label-glossary-down.sql
SET NAMES utf8mb4;

INSERT INTO translation_memory (source_hash, target_lang, source_text, translated_text, provider, is_override, created_at, updated_at)
VALUES
{values}
ON DUPLICATE KEY UPDATE
    translated_text = IF(provider = 'correction', translated_text, VALUES(translated_text)),
    is_override = IF(provider = 'correction', is_override, 1),
    updated_at = IF(provider = 'correction', updated_at, UTC_TIMESTAMP()),
    provider = IF(provider = 'correction', provider, 'glossary');

-- Web and app drop their saved translations when this number changes.
INSERT INTO translation_memory_version (id, version) VALUES (1, 1) ON DUPLICATE KEY UPDATE version = version + 1;
""", encoding='utf-8')
OUT.with_name(OUT.stem + '-down.sql').write_text("""-- Undo 2026-11-12-ui-label-glossary.sql: removes the glossary rows; those labels go back to machine translation.
-- Hand corrections (provider 'correction') are not touched. Recycle the API app pool afterwards.
DELETE FROM translation_memory WHERE provider = 'glossary';
INSERT INTO translation_memory_version (id, version) VALUES (1, 1) ON DUPLICATE KEY UPDATE version = version + 1;
""", encoding='utf-8')
print(f'{len(seen)} labels, {len(rows)} rows -> {OUT.name}')
for p in problems:
    print('  ' + p)
sys.exit(1 if any('needs' in p or 'lost' in p or 'duplicate' in p for p in problems) else 0)
