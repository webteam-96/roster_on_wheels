"""Lists every fixed text written in the app's code (lib/**/*.dart) into lib/core/i18n/ui_strings.g.dart.

Only these strings are machine translated (LiveTranslator): data shown in a Text (club names, member names, what
members write) is never in the code, so it stays as entered. Run after adding or changing UI text:

    python -I tool/gen_ui_strings.py
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / 'lib' / 'core' / 'i18n' / 'ui_strings.g.dart'
# Single- or double-quoted literals without interpolation ($); the escapes \n, \' and \" are kept, others skipped.
LIT = re.compile(r"""(?<![\w$r])'((?:[^'\\$\n]|\\.){2,})'|(?<![\w$r])"((?:[^"\\$\n]|\\.){2,})\"""")
ESCAPES = {'n': '\n', "'": "'", '"': '"'}


def unescape(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == '\\':
            if i + 1 >= len(s) or s[i + 1] not in ESCAPES:
                return None
            out.append(ESCAPES[s[i + 1]])
            i += 2
        else:
            out.append(s[i])
            i += 1
    return ''.join(out)
LETTERS = re.compile(r'[A-Za-z]{2,}')
# Paths, URLs, assets, map keys and identifiers are never shown as text.
SKIP = re.compile(r'^(/|package:|dart:|https?:|#|[a-z]+[A-Z_][A-Za-z_]*$|[a-z_]+\.[a-z_.]+$|[\w.-]+\.(png|svg|jpg|json|ttf)$)')

found = set()
for f in (ROOT / 'lib').rglob('*.dart'):
    if f == OUT:
        continue
    for line in f.read_text(encoding='utf-8').splitlines():
        if line.lstrip().startswith(('import ', 'export ', 'part ', '//')):
            continue
        for m in LIT.finditer(line):
            s = unescape(m.group(1) or m.group(2))
            if s and LETTERS.search(s) and not SKIP.match(s.strip()):
                found.add(s)

body = '\n'.join("  '" + s.replace("'", "\\'").replace('\n', '\\n') + "'," for s in sorted(found))
OUT.write_text(
    '// GENERATED by tool/gen_ui_strings.py: every fixed text in the app code. Do not edit by hand.\n'
    '// Only these are machine translated, so data (names, club names, posts) stays as entered.\n'
    'const uiStrings = <String>{\n' + body + '\n};\n',
    encoding='utf-8', newline='\n')
print(len(found), 'strings')
