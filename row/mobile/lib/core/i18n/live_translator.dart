import 'dart:convert';
import 'package:flutter/widgets.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:http/http.dart' as http;
import 'package:shared_preferences/shared_preferences.dart';
import '../brand/brand.dart';
import '../constants/app_constants.dart';
import 'ui_strings.g.dart';

/// Sends English strings to the translation service and returns them in [target], same order; null on failure.
typedef TranslateSender = Future<List<String>?> Function(String target, List<String> texts);

/// UI language for the app (N13, owner decision 2026-10-22: machine translation, no hand-written files).
/// The same service as the web: the admin's `POST /api/i18n/translate`, with the member's sign-in token.
/// Translations are cached per language on the device; a string not cached yet shows in English and is sent in
/// the next batch (every 300 ms, up to 300 strings), then the screens that use it redraw.
/// Only text written in the app's code is translated ([uiStrings], generated by `tool/gen_ui_strings.py`):
/// names, club names and what members write stay as entered. Text built at run time ('\$n members') stays English.
class LiveTranslator extends ChangeNotifier {
  LiveTranslator({TranslateSender? send, Set<String>? known})
      : _send = send ?? _post,
        _known = known ?? uiStrings;

  static final LiveTranslator instance = LiveTranslator();

  static const _languageKey = 'ui_language';
  static const _batch = 300;

  final TranslateSender _send;
  final Set<String> _known;
  String _language = 'en';
  Map<String, String> _cache = {};
  final _pending = <String>{};
  final _failed = <String>{}; // not retried until the next start
  Timer? _timer;

  String get language => _language;
  bool get active => _language != 'en';

  Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    _language = prefs.getString(_languageKey) ?? 'en';
    _cache = _decode(prefs.getString(_cacheKey(_language)));
    notifyListeners();
  }

  Future<void> setLanguage(String code) async {
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_languageKey, code);
    _language = code;
    _cache = _decode(prefs.getString(_cacheKey(code)));
    _pending.clear();
    _failed.clear();
    notifyListeners();
  }

  /// The text in the chosen language when known, else the text itself (and it is queued for translation).
  String lookup(String text) {
    if (!active || !_known.contains(text) || !_worthTranslating(text)) return text;
    final hit = _cache[text];
    if (hit != null) return hit;
    if (!_failed.contains(text) && _pending.add(text)) _timer ??= Timer(const Duration(milliseconds: 300), _flush);
    return text;
  }

  Future<void> _flush() async {
    _timer = null;
    final batch = _pending.take(_batch).toList();
    _pending.removeAll(batch);
    final target = _language;
    final out = await _send(target, batch).catchError((_) => null);
    if (target != _language) return; // the member switched language meanwhile
    if (out == null || out.length != batch.length) {
      _failed.addAll(batch);
    } else {
      for (var i = 0; i < batch.length; i++) {
        _cache[batch[i]] = out[i];
      }
      final prefs = await SharedPreferences.getInstance();
      await prefs.setString(_cacheKey(target), jsonEncode(_cache));
      notifyListeners();
    }
    if (_pending.isNotEmpty) _timer ??= Timer(const Duration(milliseconds: 300), _flush);
  }

  static String _cacheKey(String language) => 'ui_tr_$language';

  static Map<String, String> _decode(String? raw) {
    if (raw == null) return {};
    try {
      return (jsonDecode(raw) as Map).map((k, v) => MapEntry(k as String, v as String));
    } catch (_) {
      return {};
    }
  }

  // Numbers, dates, codes and names-only text gain nothing from translation.
  static final _letters = RegExp(r'[A-Za-z]{2,}');
  static bool _worthTranslating(String text) => text.trim().length > 1 && _letters.hasMatch(text);

  static Future<List<String>?> _post(String target, List<String> texts) async {
    final origin = Brand.current.adminOrigin.isNotEmpty
        ? Brand.current.adminOrigin
        : const String.fromEnvironment('ADMIN_BASE_URL');
    if (origin.isEmpty) return null;
    String? token;
    try {
      token = await const FlutterSecureStorage().read(key: AppConstants.tokenKey);
    } catch (_) {}
    final res = await http
        .post(Uri.parse('$origin/api/i18n/translate'),
            headers: {'Content-Type': 'application/json', if (token != null) 'Authorization': 'Bearer $token'},
            body: jsonEncode({'target': target, 'source': 'en', 'q': texts}))
        .timeout(const Duration(seconds: 15));
    if (res.statusCode != 200) return null;
    return ((jsonDecode(res.body) as Map)['translations'] as List).map((e) => e.toString()).toList();
  }
}

/// Puts [LiveTranslator] above the app so every [Text] redraws when new translations arrive.
class TranslationScope extends InheritedNotifier<LiveTranslator> {
  const TranslationScope({super.key, required LiveTranslator translator, required super.child})
      : super(notifier: translator);

  /// The text in the chosen language; without a scope above (tests, previews) the text unchanged.
  static String of(BuildContext context, String text) =>
      context.dependOnInheritedWidgetOfExactType<TranslationScope>()?.notifier?.lookup(text) ?? text;
}
