    // Overload that accepts a list of CC addresses — filters empties, dedupes case-insensitively,
    // and also excludes the primary To address from the CC list to avoid duplicate delivery.
    private Task SendEmailAsync(string toEmail, string subject, string htmlBody, IEnumerable<string>? ccEmails, bool throwOnFailure = false)
    {
        var list = (ccEmails ?? Array.Empty<string>())
            .Where(e => !string.IsNullOrWhiteSpace(e))
            .Select(e => e.Trim())
            .Where(e => !string.Equals(e, toEmail, StringComparison.OrdinalIgnoreCase))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();
        var joined = list.Count == 0 ? null : string.Join(",", list);
        return SendEmailAsync(toEmail, subject, htmlBody, joined, throwOnFailure);
    }

    // Club/District-tagged send for the scheduled communication emails (announcements, events,
    // newsletters, projects). Stamps email_log.fk_club_id/fk_district_id so Club/District admins
    // can see their own email log. Everything else uses the untagged SendEmailAsync.
    public async Task SendScopedEmailAsync(string toEmail, string subject, string htmlBody, int? clubId, int? districtId)
        => await SendEmailAsync(toEmail, subject, htmlBody, ccEmail: null, throwOnFailure: false, clubId: clubId, districtId: districtId);

    private async Task SendEmailAsync(string toEmail, string subject, string htmlBody, string? ccEmail = null, bool throwOnFailure = false, int? clubId = null, int? districtId = null)
    {
        long? logId = null;
        try
        {
            logId = await BrevoEmailLog.InsertPendingAsync(_configuration, toEmail, ccEmail, subject, htmlBody, BrevoEmailLog.ClassifyType(subject), _logger, clubId, districtId);
            var brevoMessageId = await SendViaBrevoAsync(toEmail, subject, htmlBody, ccEmail, null, null);
            await BrevoEmailLog.MarkSentAsync(_configuration, logId, brevoMessageId, _logger);
            _logger.LogInformation("Email sent successfully to {Email} (Brevo id={Id})", toEmail, brevoMessageId);
        }
        catch (Exception ex)
        {
            await BrevoEmailLog.MarkFailedAsync(_configuration, logId, ex.Message, _logger);
            _logger.LogError(ex, "Failed to send email to {Email}", toEmail);
            if (throwOnFailure) throw;
        }
    }

    private async Task<string?> SendViaBrevoAsync(
        string toEmail,
        string subject,
        string htmlBody,
        string? ccEmail,
        byte[]? attachmentBytes,
        string? attachmentFileName)
    {
        var brevo = _configuration.GetSection("Brevo");
        var apiKey = brevo["ApiKey"] ?? throw new InvalidOperationException("Brevo:ApiKey is not configured.");
        var apiUrl = brevo["ApiUrl"] ?? "https://api.brevo.com/v3/smtp/email";
        var senderEmail = brevo["SenderEmail"] ?? RotaryApi.Services.Brand.NoReplyEmail;
        var senderName = brevo["SenderName"] ?? "ROW";

        var ccList = new List<object>();
        if (!string.IsNullOrWhiteSpace(ccEmail))
        {
            foreach (var addr in ccEmail.Split(new[] { ',', ';' }, StringSplitOptions.RemoveEmptyEntries))
            {
                var trimmed = addr.Trim();
                if (trimmed.Length > 0 && !string.Equals(trimmed, toEmail, StringComparison.OrdinalIgnoreCase))
                    ccList.Add(new { email = trimmed });
            }
        }

        var payload = new Dictionary<string, object?>
        {
            ["sender"] = new { name = senderName, email = senderEmail },
            ["to"] = new[] { new { email = toEmail } },
            ["subject"] = subject,
            ["htmlContent"] = htmlBody
        };
        if (ccList.Count > 0) payload["cc"] = ccList;
        if (attachmentBytes != null && !string.IsNullOrEmpty(attachmentFileName))
        {
            payload["attachment"] = new[]
            {
                new { name = attachmentFileName, content = Convert.ToBase64String(attachmentBytes) }
            };
        }

        var json = JsonSerializer.Serialize(payload);
        using var http = _httpClientFactory.CreateClient();
        // A photo-rich CMR PDF (~13 MB raw → ~18 MB base64 in the JSON body) can take well over
        // 30 s to upload, so the 30 s timeout was aborting the send mid-upload (client-side
        // "HttpClient.Timeout … elapsing", or a Brevo 522 when the edge gave up first). Give
        // attachment sends a much longer budget; plain emails keep the fast 30 s.
        bool hasAttachment = attachmentBytes != null && attachmentBytes.Length > 0;
        var brevoTimeoutSec = int.TryParse(brevo["AttachmentTimeoutSeconds"], out var cfgTimeout) && cfgTimeout > 0
            ? cfgTimeout : 180;
        http.Timeout = TimeSpan.FromSeconds(hasAttachment ? brevoTimeoutSec : 30);
        using var req = new HttpRequestMessage(HttpMethod.Post, apiUrl)
        {
            Content = new StringContent(json, Encoding.UTF8, "application/json")
        };
        req.Headers.Accept.Add(new MediaTypeWithQualityHeaderValue("application/json"));
        req.Headers.Add("api-key", apiKey);

        using var resp = await http.SendAsync(req);
        var respBody = await resp.Content.ReadAsStringAsync();
        if (!resp.IsSuccessStatusCode)
            throw new HttpRequestException($"Brevo {(int)resp.StatusCode}: {respBody}");

        try
        {
            using var doc = JsonDocument.Parse(respBody);
            if (doc.RootElement.TryGetProperty("messageId", out var mid)) return mid.GetString();
        }
        catch { /* ignore parse failure — messageId is optional metadata */ }
        return null;
    }
