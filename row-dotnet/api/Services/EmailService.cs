internal static class BrevoEmailLog
{
    // Best-effort classification by subject text. Order matters — more specific patterns first.
    // Reflects every IEmailService.Send* + every external SendGenericEmailAsync caller in the codebase.
    public static string ClassifyType(string? subject)
    {
        if (string.IsNullOrWhiteSpace(subject)) return "Other";
        var s = subject;

        // Mass campaigns are prefixed with "Mass Email:" by ClubMassEmailService.SendAsync — most reliable signal.
        if (s.Contains("Mass Email", StringComparison.OrdinalIgnoreCase)) return "Mass Email";

        // OTPs (auth + directory + cashfree). Catch first — common substring.
        if (s.Contains("OTP", StringComparison.Ordinal) || s.Contains("One Time Password", StringComparison.OrdinalIgnoreCase)) return "OTP";

        // Public-directory data collection (saved/reminder).
        if (s.Contains("Data Collection", StringComparison.OrdinalIgnoreCase)
            || s.Contains("District Directory", StringComparison.OrdinalIgnoreCase)
            || s.Contains("Submission Received", StringComparison.OrdinalIgnoreCase)) return "Data Collection";

        // Citation auto-points nightly job.
        if (s.Contains("Auto Calculate", StringComparison.OrdinalIgnoreCase)
            || s.Contains("District awards Points", StringComparison.OrdinalIgnoreCase)
            || s.Contains("Citation", StringComparison.OrdinalIgnoreCase)) return "Citation";

        // Club Monthly Report (with PDF attachment).
        if (s.Contains("Monthly Report", StringComparison.OrdinalIgnoreCase) || s.Contains("CMR", StringComparison.OrdinalIgnoreCase)) return "Monthly Report";

        // Newsletters / e-bulletins.
        if (s.Contains("Newsletter", StringComparison.OrdinalIgnoreCase) || s.Contains("eBulletin", StringComparison.OrdinalIgnoreCase)) return "Newsletter";

        // Beneficiary approval workflow.
        if (s.Contains("Beneficiary", StringComparison.OrdinalIgnoreCase)) return "Beneficiary";

        // Cashfree KYC notifications.
        if (s.Contains("KYC", StringComparison.Ordinal) || s.Contains("Cashfree", StringComparison.OrdinalIgnoreCase)) return "KYC";

        // Club website lifecycle.
        if (s.Contains("Club Website", StringComparison.OrdinalIgnoreCase) || s.Contains("Website", StringComparison.OrdinalIgnoreCase)) return "Club Website";

        // Password lifecycle.
        if (s.Contains("Password Reset", StringComparison.OrdinalIgnoreCase) || s.Contains("Reset Password", StringComparison.OrdinalIgnoreCase)) return "Password Reset";
        if (s.Contains("Password Changed", StringComparison.OrdinalIgnoreCase)) return "Password Changed";

        // Role assignment / login credential drops.
        if (s.Contains("SuperAdmin", StringComparison.OrdinalIgnoreCase)) return "SuperAdmin";
        if (s.Contains("Zonal Co-ordinator", StringComparison.OrdinalIgnoreCase) || s.Contains("Zonal Coordinator", StringComparison.OrdinalIgnoreCase)) return "Zonal Coordinator";
        if (s.Contains("Club Admin", StringComparison.OrdinalIgnoreCase) && s.Contains("Designation", StringComparison.OrdinalIgnoreCase)) return "Club Admin Assignment";
        if (s.Contains("Login Credentials", StringComparison.OrdinalIgnoreCase) || s.Contains("Login Details", StringComparison.OrdinalIgnoreCase)) return "Login Credentials";

        // Welcome / role-change notifications.
        if (s.Contains("Welcome", StringComparison.OrdinalIgnoreCase)) return "Welcome";
        if (s.Contains("Removed", StringComparison.OrdinalIgnoreCase) || s.Contains("Revoked", StringComparison.OrdinalIgnoreCase)) return "Role / Membership Removed";

        // Club Leadership reminders.
        if (s.Contains("Club Leadership", StringComparison.OrdinalIgnoreCase) || s.Contains("Leadership", StringComparison.OrdinalIgnoreCase)) return "Club Leadership";

        // Generic reminders.
        if (s.Contains("Reminder", StringComparison.OrdinalIgnoreCase)) return "Reminder";

        return "Other";
    }

    public static async Task<long?> InsertPendingAsync(
        IConfiguration cfg, string toEmail, string? ccEmail, string subject, string htmlBody, string? emailType, ILogger logger,
        int? clubId = null, int? districtId = null)
    {
        try
        {
            var connStr = cfg.GetConnectionString("DefaultConnection");
            if (string.IsNullOrWhiteSpace(connStr)) return null;
            using var conn = new MySqlConnector.MySqlConnection(connStr);
            await conn.OpenAsync();
            var sql = @"INSERT INTO email_log (recipient_email, cc_emails, subject, body_html, email_type, status, fk_club_id, fk_district_id, sent_at)
                        VALUES (@To, @Cc, @Subject, @Body, @Type, 'Pending', @ClubId, @DistrictId, NOW());
                        SELECT LAST_INSERT_ID();";
            var id = await Dapper.SqlMapper.ExecuteScalarAsync<long>(conn, sql, new
            {
                To = toEmail,
                Cc = ccEmail,
                Subject = subject,
                Body = htmlBody,
                Type = emailType,
                ClubId = clubId,
                DistrictId = districtId
            });
            return id;
        }
        catch (Exception ex)
        {
            logger.LogWarning(ex, "email_log: InsertPending failed for {Email}", toEmail);
            return null;
        }
    }

    public static async Task MarkSentAsync(IConfiguration cfg, long? logId, string? brevoMessageId, ILogger logger)
    {
        if (!logId.HasValue) return;
        try
        {
            var connStr = cfg.GetConnectionString("DefaultConnection");
            if (string.IsNullOrWhiteSpace(connStr)) return;
            using var conn = new MySqlConnector.MySqlConnection(connStr);
            await conn.OpenAsync();
            await Dapper.SqlMapper.ExecuteAsync(conn,
                "UPDATE email_log SET status='Sent', brevo_message_id=@Mid, sent_at=NOW() WHERE pk_id=@Id",
                new { Mid = brevoMessageId, Id = logId.Value });
        }
        catch (Exception ex) { logger.LogWarning(ex, "email_log: MarkSent failed for id={Id}", logId); }
    }

    public static async Task MarkFailedAsync(IConfiguration cfg, long? logId, string error, ILogger logger)
    {
        if (!logId.HasValue) return;
        try
        {
            var connStr = cfg.GetConnectionString("DefaultConnection");
            if (string.IsNullOrWhiteSpace(connStr)) return;
            using var conn = new MySqlConnector.MySqlConnection(connStr);
            await conn.OpenAsync();
            var trimmed = error.Length > 1000 ? error[..1000] : error;
            await Dapper.SqlMapper.ExecuteAsync(conn,
                "UPDATE email_log SET status='Failed', error_message=@Err, sent_at=NOW() WHERE pk_id=@Id",
                new { Err = trimmed, Id = logId.Value });
        }
        catch (Exception ex) { logger.LogWarning(ex, "email_log: MarkFailed failed for id={Id}", logId); }
    }
