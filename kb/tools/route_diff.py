"""Compare the RIZones .NET API routes with the ROW NestJS routes.

.NET routes are parsed from the C# controllers; ROW routes come from the
"Mapped {...}" lines Nest prints at start-up (so inherited routes count).

usage: python -I route_diff.py <csharp Controllers dir> <nest boot log> <out.md>
"""
import os
import re
import sys
from collections import defaultdict

VERB = re.compile(r'\[Http(Get|Post|Put|Patch|Delete)(?:\(\s*"([^"]*)"[^)]*\))?\]')
ROUTE = re.compile(r'\[Route\(\s*"([^"]*)"')
CLASS = re.compile(r'\bclass\s+(\w+)Controller\b')
METHOD = re.compile(r'\b(?:public|private|protected|internal)\b[^=;]*\(')
MAPPED = re.compile(r'Mapped \{([^,]+), (\w+)\}')
ANSI = re.compile(r'\x1b\[[0-9;]*m')


def norm(path):
    path = path.strip().lstrip("~").strip("/").lower()
    path = re.sub(r'\{[^}]*\}', '{}', path)
    path = re.sub(r':\w+\??', '{}', path)
    return path


def join(prefix, tmpl):
    if tmpl.startswith("/") or tmpl.startswith("~/"):
        return tmpl
    if not tmpl:
        return prefix
    return prefix.rstrip("/") + "/" + tmpl


def dotnet_routes(folder):
    routes = []  # (verb, path, controller)
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".cs"):
            continue
        text = open(os.path.join(folder, name), encoding="utf-8-sig").read()
        lines = text.splitlines()
        ctrl, prefixes, pending_routes, pending_verbs = None, [], [], []
        for line in lines:
            m = CLASS.search(line)
            if m:
                ctrl = m.group(1)
                prefixes = [p.replace("[controller]", ctrl) for p in pending_routes] or [""]
                pending_routes, pending_verbs = [], []
                continue
            for r in ROUTE.findall(line):
                pending_routes.append(r)
            for verb, tmpl in VERB.findall(line):
                pending_verbs.append((verb.upper(), tmpl))
            if ctrl and METHOD.search(line) and not line.strip().startswith("["):
                if pending_verbs:
                    for verb, tmpl in pending_verbs:
                        tmpls = [tmpl] if tmpl or not pending_routes else pending_routes
                        for t in tmpls:
                            for p in prefixes:
                                routes.append((verb, join(p, t), ctrl))
                pending_routes, pending_verbs = [], []
    return routes


def nest_routes(log):
    out = []
    for line in open(log, encoding="utf-8", errors="replace"):
        m = MAPPED.search(ANSI.sub("", line))
        if m:
            out.append((m.group(2).upper(), m.group(1)))
    return out


def main(cs_dir, log, out_md):
    net = dotnet_routes(cs_dir)
    row = nest_routes(log)
    row_keys = {(v, norm(p)) for v, p in row}
    net_keys = {(v, norm(p)) for v, p, _ in net}

    missing = defaultdict(list)
    for v, p, c in net:
        if (v, norm(p)) not in row_keys:
            missing[c].append(f"{v} {p}")
    per_ctrl = defaultdict(int)
    for _, _, c in net:
        per_ctrl[c] += 1
    extra = sorted({f"{v} {p}" for v, p in row if (v, norm(p)) not in net_keys})

    done = sum(1 for k in net_keys if k in row_keys)
    lines = [
        "# API routes: RIZones .NET vs ROW NestJS",
        "",
        "Generated by `kb/tools/route_diff.py` (rerun with `kb/rebuild.sh`). Do not edit by hand.",
        "",
        f"- .NET routes (unique verb + path): **{len(net_keys)}**",
        f"- ROW routes mapped at boot: **{len(row_keys)}**",
        f"- .NET routes present in ROW: **{done}** ({done * 100 // max(len(net_keys), 1)}%)",
        f"- .NET routes missing in ROW: **{len(net_keys) - done}** in {len(missing)} controllers",
        f"- ROW-only routes: **{len(extra)}**",
        "",
        "## Missing in ROW, by controller",
        "",
        "| Controller | Missing / total | Routes |",
        "|---|---|---|",
    ]
    for c in sorted(missing, key=lambda c: (-len(missing[c]), c)):
        rs = sorted(set(missing[c]))
        shown = "<br>".join(f"`{r}`" for r in rs[:12]) + ("<br>…" if len(rs) > 12 else "")
        lines.append(f"| {c} | {len(rs)} / {per_ctrl[c]} | {shown} |")
    lines += ["", "## ROW-only routes", ""] + [f"- `{r}`" for r in extra] + [""]
    open(out_md, "w", encoding="utf-8").write("\n".join(lines))
    print(f"net={len(net_keys)} row={len(row_keys)} matched={done} missing_ctrls={len(missing)} extra={len(extra)}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
