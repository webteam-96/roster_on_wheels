"""Index every project document (Markdown and text specs) by path, size and headings.

usage: python -I docs_index.py <out.md> <root> [<root> ...]
"""
import os
import re
import sys

SKIP_DIRS = {"node_modules", ".next", "build", ".dart_tool", "bin", "obj", "Pods", ".gradle",
             "graphify-out", ".git", "dist", "kb", "licenses", "third_party", ".github"}
HEADING = re.compile(r"^(#{1,2})\s+(.*\S)")


def outline(path):
    heads, first = [], ""
    for line in open(path, encoding="utf-8", errors="replace"):
        m = HEADING.match(line)
        if m:
            heads.append(("  " if len(m.group(1)) == 2 else "") + m.group(2).strip("# "))
        elif not first and line.strip():
            first = line.strip()[:120]
    return heads, first


def main(out_md, *roots):
    L = ["# Document index", "",
         "Generated by `kb/tools/docs_index.py` (rerun with `kb/rebuild.sh`). Headings only (H1/H2);",
         "open the file for the text. Do not edit by hand.", ""]
    for root in roots:
        docs = []
        for d, dirs, names in os.walk(root):
            dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
            for n in sorted(names):
                if n.lower().endswith((".md", ".txt")) and not n.startswith("README_") and n != "CHANGELOG.md":
                    docs.append(os.path.join(d, n))
        L += [f"## {root} ({len(docs)} documents)", ""]
        for p in docs:
            rel = p.replace("\\", "/")
            heads, first = outline(p)
            L.append(f"- **{rel}** ({os.path.getsize(p) // 1024} KB)")
            if heads:
                L += [f"  - {h}" for h in heads[:25]]
                if len(heads) > 25:
                    L.append(f"  - … {len(heads) - 25} more headings")
            elif first:
                L.append(f"  - _{first}_")
        L.append("")
    open(out_md, "w", encoding="utf-8").write("\n".join(L))
    print(f"indexed {sum(1 for l in L if l.startswith('- **'))} documents")


if __name__ == "__main__":
    main(*sys.argv[1:])
