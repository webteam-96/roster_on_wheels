"""Compare a ROW client app with its RIZones original.

Lists files only in one side and changed files (lines added/removed), and checks
every "/api/..." path the ROW client calls against the ROW API route table.

usage: python -I app_diff.py <title> <ref dir> <row dir> <nest boot log> <out.md> [ext,ext]
"""
import difflib
import os
import re
import sys

SKIP_DIRS = {"node_modules", ".next", "build", ".dart_tool", "bin", "obj", "out", "Pods",
             ".gradle", "graphify-out", ".git", "dist", "coverage"}
API_LIT = re.compile(r"""['"`](/?api/[^'"`\s?#]*)""")
INTERP = re.compile(r"\$\{[^}]*\}|\$\w+|\{[^}]*\}")
MAPPED = re.compile(r"Mapped \{([^,]+), (\w+)\}")
ANSI = re.compile(r"\x1b\[[0-9;]*m")


def files(root, exts):
    out = {}
    for d, dirs, names in os.walk(root):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
        for n in names:
            if os.path.splitext(n)[1] in exts:
                p = os.path.join(d, n)
                out[os.path.relpath(p, root).replace("\\", "/")] = p
    return out


def read(p):
    return open(p, encoding="utf-8", errors="replace").read().splitlines()


def seg_pattern(path):
    path = path.strip("/").lower().rstrip("*").rstrip(".")
    # an interpolation glued to a segment is a query string or suffix ("weblinks${qs}")
    path = re.sub(r"(?<=[\w-])(\$\{[^}]*\}?|\$\w+)", "", path)
    path = INTERP.sub("{}", path)
    path = re.sub(r":\w+\??", "{}", path)
    return [s for s in path.split("/") if s]


def route_table(log):
    routes = set()
    for line in open(log, encoding="utf-8", errors="replace"):
        m = MAPPED.search(ANSI.sub("", line))
        if m:
            routes.add(tuple(seg_pattern(m.group(1))))
    return routes


def matches(call, routes):
    """A client path matches if some route has the same segments ({} = any).
    A trailing {} in the call may be a query or sub-path built at runtime."""
    for r in routes:
        # base-URL constants ("api/clubs/{}/banners" + "/" + id) match any longer route
        if len(r) >= len(call) and all(a == b or a == "{}" or b == "{}" for a, b in zip(call, r)):
            return True
        if len(r) == len(call) and all(a == b or a == "{}" or b == "{}" for a, b in zip(call, r)):
            return True
        if call and call[-1] == "{}" and len(r) >= len(call) - 1 and \
                all(a == b or a == "{}" or b == "{}" for a, b in zip(call[:-1], r)):
            return True
    return False


def main(title, ref, row, log, out_md, exts=".dart"):
    exts = {e if e.startswith(".") else "." + e for e in exts.split(",")}
    rf, wf = files(ref, exts), files(row, exts)
    only_ref = sorted(set(rf) - set(wf))
    only_row = sorted(set(wf) - set(rf))
    changed = []
    for k in sorted(set(rf) & set(wf)):
        a, b = read(rf[k]), read(wf[k])
        if a != b:
            add = rem = 0
            for l in difflib.unified_diff(a, b, lineterm="", n=0):
                if l.startswith("+") and not l.startswith("+++"):
                    add += 1
                elif l.startswith("-") and not l.startswith("---"):
                    rem += 1
            changed.append((k, add, rem))

    routes = route_table(log)
    calls = {}
    for k, p in wf.items():
        for m in API_LIT.finditer("\n".join(read(p))):
            raw = m.group(1)
            seg = tuple(seg_pattern(raw))
            if len(seg) >= 2:
                calls.setdefault(seg, (raw, k))
    unmatched = sorted((v for s, v in calls.items() if not matches(list(s), routes)), key=lambda v: v[0])

    L = [f"# {title}: RIZones original vs ROW", "",
         "Generated by `kb/tools/app_diff.py` (rerun with `kb/rebuild.sh`). Do not edit by hand.", "",
         f"- Source files: original **{len(rf)}**, ROW **{len(wf)}** ({', '.join(sorted(exts))})",
         f"- Only in original: **{len(only_ref)}** · only in ROW: **{len(only_row)}** · changed: **{len(changed)}** · identical: **{len(set(rf) & set(wf)) - len(changed)}**",
         f"- Distinct `/api/...` paths the ROW client calls: **{len(calls)}** · not served by the ROW API: **{len(unmatched)}**", "",
         "## API paths the ROW client calls that the ROW API does not serve", "",
         "Static literals only; paths built from variables are not seen. Payments endpoints are expected here until Payments is ported.", "",
         "| Path | First seen in |", "|---|---|"]
    L += [f"| `{raw}` | {f} |" for raw, f in unmatched]
    L += ["", "## Only in the original", ""] + [f"- {f}" for f in only_ref]
    L += ["", "## Only in ROW", ""] + [f"- {f}" for f in only_row]
    L += ["", "## Changed files (lines + / -)", "", "| File | + | - |", "|---|---|---|"]
    L += [f"| {f} | {a} | {r} |" for f, a, r in sorted(changed, key=lambda c: -(c[1] + c[2]))]
    open(out_md, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print(f"{title}: ref={len(rf)} row={len(wf)} only_ref={len(only_ref)} only_row={len(only_row)} changed={len(changed)} calls={len(calls)} unmatched={len(unmatched)}")


if __name__ == "__main__":
    main(*sys.argv[1:])
